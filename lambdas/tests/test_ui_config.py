"""Regression guard: the shipped UI must carry no endpoint literals.

The demo-blocking defect this replaces was a pair of API Gateway URLs typed
into ``ui/*.html``. They pointed at a deleted personal-account deployment, the
static-site stack shipped the files verbatim, and a fresh deploy therefore
produced a UI that silently called endpoints which no longer existed.

The endpoints now arrive as ``config.js``, generated by the static-site stack
from its own outputs. The *behaviour* of that loader — validate, show a banner,
run the PKCE redirect — is browser-only JavaScript with no Python surface, and
is deliberately not simulated here. What is testable, and what actually failed
before, is the invariant: no literal endpoint in the tree, and both pages
wired to the generated config rather than to constants of their own.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

UI = Path(__file__).resolve().parents[2] / "ui"
PAGES = ("upload.html", "review.html")

#: Anything that looks like a baked-in AWS endpoint.
ENDPOINT_LITERAL = re.compile(r"execute-api|amazonaws\.com|amazoncognito\.com")


@pytest.mark.parametrize("name", [p.name for p in sorted(UI.iterdir()) if p.is_file()])
def test_no_endpoint_literal_survives_in_the_ui(name: str) -> None:
    found = ENDPOINT_LITERAL.findall((UI / name).read_text(encoding="utf-8"))
    assert not found, f"{name} hardcodes an endpoint: {sorted(set(found))}"


@pytest.mark.parametrize("page", PAGES)
def test_each_page_loads_the_generated_config_before_its_own_script(page: str) -> None:
    html = (UI / page).read_text(encoding="utf-8")
    assert 'src="config.js"' in html
    assert 'src="auth.js"' in html
    assert html.index('src="config.js"') < html.index('src="auth.js"')


@pytest.mark.parametrize("page", PAGES)
def test_each_page_boots_through_the_config_and_auth_gate(page: str) -> None:
    """``RFP.start`` validates config and completes login before init() runs,
    which is what makes a missing config a visible banner instead of a
    scattering of failed fetches."""
    html = (UI / page).read_text(encoding="utf-8")
    assert "RFP.start(init)" in html
    assert re.search(r"^\s*init\(\);", html, re.MULTILINE) is None


def test_the_config_contract_matches_what_the_stack_generates() -> None:
    """auth.js refuses to run on a config missing any of these keys; the
    static-site stack is the only thing that writes them. If the two lists
    drift, a deploy produces a page that banners instead of loading."""
    auth_js = (UI / "auth.js").read_text(encoding="utf-8")
    stack = (
        Path(__file__).resolve().parents[2] / "infra" / "lib" / "static-site-stack.ts"
    ).read_text(encoding="utf-8")

    block = auth_js.split("REQUIRED_KEYS = [", 1)[1].split("]", 1)[0]
    required = re.findall(r"'([^']+)'", block)

    assert "uploadApiUrl" in required and "reviewApiUrl" in required
    assert any(k.startswith("auth.") for k in required)
    for key in required:
        leaf = key.rsplit(".", 1)[-1]
        assert f"{leaf}:" in stack, f"config.js never sets {key}, but auth.js requires it"
