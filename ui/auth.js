/**
 * Deploy-time config + Cognito Hosted UI login for the RFP Copilot pages.
 *
 * Two problems solved here, both of which used to break a fresh deploy:
 *
 * 1. No endpoint literals. Every URL comes from `window.RFP_CONFIG`, which the
 *    static-site stack generates at deploy time (config.js, written beside
 *    these pages from the stack's own outputs). If config.js is absent or
 *    incomplete the page says so on screen and makes no calls at all — the old
 *    failure mode was a silent fetch against a deleted account's endpoint.
 *
 * 2. Both HTTP APIs require a Cognito id token. Login is the authorization-code
 *    grant with PKCE (S256): no client secret, no implicit flow, nothing
 *    long-lived in storage. An expired or rejected token sends the browser back
 *    to the Hosted UI rather than failing a fetch quietly.
 *
 * Vanilla, no dependencies, no build step. Loaded by both pages as
 *   <script src="config.js"></script><script src="auth.js"></script>
 */
(function (global) {
  'use strict';

  var STORE_TOKEN = 'rfp_id_token';
  var STORE_VERIFIER = 'rfp_pkce_verifier';
  var STORE_STATE = 'rfp_oauth_state';
  var STORE_RETURN = 'rfp_return_to';

  // Mirrors the object built in infra/lib/static-site-stack.ts. A key listed
  // here and missing from config.js is a hard stop, not a warning.
  var REQUIRED_KEYS = [
    'uploadApiUrl',
    'reviewApiUrl',
    'auth.region',
    'auth.userPoolId',
    'auth.userPoolClientId',
    'auth.hostedUiUrl',
  ];

  var cfg = null;

  // ---- fatal banner -------------------------------------------------------

  /**
   * Show an unmissable, non-dismissable banner and stop. The human is demoing
   * this: a blank page plus a console error is the worst possible outcome, so
   * every unrecoverable condition lands here with the operator fix spelled out.
   */
  function fatal(title, detail) {
    var existing = document.getElementById('rfp-fatal');
    if (existing) { existing.remove(); }
    var el = document.createElement('div');
    el.id = 'rfp-fatal';
    el.setAttribute('role', 'alert');
    el.style.cssText =
      'position:relative;z-index:9999;background:#f8d7da;color:#721c24;' +
      'border-bottom:3px solid #c0392b;padding:16px 24px;font-size:14px;' +
      'line-height:1.5;font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif';
    var h = document.createElement('strong');
    h.textContent = title;
    h.style.cssText = 'display:block;font-size:15px;margin-bottom:4px';
    var p = document.createElement('div');
    p.textContent = detail;
    el.appendChild(h);
    el.appendChild(p);
    document.body.insertBefore(el, document.body.firstChild);
    return null;
  }

  // ---- config -------------------------------------------------------------

  function dig(obj, dotted) {
    return dotted.split('.').reduce(function (acc, key) {
      return acc == null ? undefined : acc[key];
    }, obj);
  }

  /** Returns the config object, or null after showing the banner. */
  function loadConfig() {
    var raw = global.RFP_CONFIG;
    if (!raw || typeof raw !== 'object') {
      return fatal(
        'Configuration missing — the UI does not know which deployment to talk to.',
        'config.js did not load or did not define RFP_CONFIG. It is generated by ' +
          'the static-site stack at deploy time; redeploy that stack, or serve ' +
          'these pages with a config.js beside them. No API calls will be made.',
      );
    }
    var missing = REQUIRED_KEYS.filter(function (key) {
      var v = dig(raw, key);
      return typeof v !== 'string' || v.trim() === '';
    });
    if (missing.length) {
      return fatal(
        'Configuration incomplete — ' + missing.length + ' required value(s) missing.',
        'config.js is missing: ' + missing.join(', ') + '. Redeploy the ' +
          'static-site stack so it regenerates from the current stack outputs.',
      );
    }
    return raw;
  }

  // ---- PKCE ---------------------------------------------------------------

  function b64url(bytes) {
    var s = '';
    for (var i = 0; i < bytes.length; i++) { s += String.fromCharCode(bytes[i]); }
    return btoa(s).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
  }

  function randomString() {
    return b64url(global.crypto.getRandomValues(new Uint8Array(32)));
  }

  function challenge(verifier) {
    return global.crypto.subtle
      .digest('SHA-256', new TextEncoder().encode(verifier))
      .then(function (buf) { return b64url(new Uint8Array(buf)); });
  }

  function redirectUri() {
    // Must match one of the callback URLs registered on the app client. Query
    // and fragment are deliberately excluded — the pre-login location is
    // restored from sessionStorage after the exchange instead.
    return global.location.origin + global.location.pathname;
  }

  function beginLogin() {
    var verifier = randomString();
    var state = randomString();
    return challenge(verifier).then(function (chal) {
      sessionStorage.setItem(STORE_VERIFIER, verifier);
      sessionStorage.setItem(STORE_STATE, state);
      sessionStorage.setItem(STORE_RETURN, global.location.pathname + global.location.search);
      var url =
        cfg.auth.hostedUiUrl +
        '/oauth2/authorize' +
        '?response_type=code' +
        '&client_id=' + encodeURIComponent(cfg.auth.userPoolClientId) +
        '&redirect_uri=' + encodeURIComponent(redirectUri()) +
        '&scope=' + encodeURIComponent(cfg.auth.scopes || 'openid email profile') +
        '&state=' + encodeURIComponent(state) +
        '&code_challenge_method=S256' +
        '&code_challenge=' + encodeURIComponent(chal);
      global.location.assign(url);
      // Never resolves: the page is navigating away.
      return new Promise(function () {});
    });
  }

  function exchangeCode(code) {
    var verifier = sessionStorage.getItem(STORE_VERIFIER);
    if (!verifier) {
      return Promise.reject(new Error('No PKCE verifier for this login attempt'));
    }
    var body = new URLSearchParams({
      grant_type: 'authorization_code',
      client_id: cfg.auth.userPoolClientId,
      code: code,
      redirect_uri: redirectUri(),
      code_verifier: verifier,
    });
    return fetch(cfg.auth.hostedUiUrl + '/oauth2/token', {
      method: 'POST',
      headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
      body: body.toString(),
    })
      .then(function (r) {
        return r.json().then(function (data) {
          if (!r.ok || !data.id_token) {
            throw new Error(data.error_description || data.error || 'token exchange failed');
          }
          return data;
        });
      })
      .then(function (data) {
        sessionStorage.setItem(STORE_TOKEN, data.id_token);
        sessionStorage.removeItem(STORE_VERIFIER);
        sessionStorage.removeItem(STORE_STATE);
        var back = sessionStorage.getItem(STORE_RETURN) || global.location.pathname;
        sessionStorage.removeItem(STORE_RETURN);
        // Drop ?code= &state= from the address bar and put the caller's own
        // query string (e.g. review.html?job=…) back where the page expects it.
        history.replaceState({}, '', back);
      });
  }

  // ---- tokens -------------------------------------------------------------

  function decodeClaims(token) {
    try {
      var part = token.split('.')[1].replace(/-/g, '+').replace(/_/g, '/');
      return JSON.parse(atob(part + '==='.slice((part.length + 3) % 4)));
    } catch (e) {
      return null;
    }
  }

  /** Token we still consider usable — 60s of slack against clock skew. */
  function validToken() {
    var token = sessionStorage.getItem(STORE_TOKEN);
    if (!token) { return null; }
    var claims = decodeClaims(token);
    if (!claims || !claims.exp || claims.exp * 1000 <= Date.now() + 60000) {
      sessionStorage.removeItem(STORE_TOKEN);
      return null;
    }
    return token;
  }

  function identity() {
    var token = sessionStorage.getItem(STORE_TOKEN);
    var claims = token ? decodeClaims(token) : null;
    return (claims && (claims.email || claims.sub)) || '';
  }

  function logout() {
    sessionStorage.removeItem(STORE_TOKEN);
    global.location.assign(
      cfg.auth.hostedUiUrl +
        '/logout?client_id=' + encodeURIComponent(cfg.auth.userPoolClientId) +
        '&logout_uri=' + encodeURIComponent(redirectUri()),
    );
  }

  // ---- authenticated calls ------------------------------------------------

  function call(baseUrl, path, method, body) {
    var token = validToken();
    if (!token) {
      // Expiry mid-session is a redirect, not a failed fetch: the Hosted UI
      // re-issues silently if the Cognito session is still alive.
      return beginLogin();
    }
    var opts = {
      method: method || 'GET',
      headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + token },
    };
    if (body) { opts.body = JSON.stringify(body); }
    return fetch(baseUrl + path, opts).then(function (r) {
      if (r.status === 401 || r.status === 403) {
        sessionStorage.removeItem(STORE_TOKEN);
        return beginLogin();
      }
      return r.json().then(
        function (data) {
          if (!r.ok) { throw new Error(data.error || r.statusText); }
          return data;
        },
        function () {
          throw new Error('HTTP ' + r.status + ' with an unreadable body');
        },
      );
    });
  }

  // ---- boot ---------------------------------------------------------------

  /**
   * Validate config, complete or start login, then hand control to the page.
   * The page's own init never runs without a usable config and a live token,
   * so no page code has to defend against either being absent.
   */
  function start(pageInit) {
    cfg = loadConfig();
    if (!cfg) { return; }
    if (!global.crypto || !global.crypto.subtle) {
      fatal(
        'This page must be served over HTTPS (or http://localhost).',
        'Web Crypto is unavailable, so the PKCE login cannot run. Opening the ' +
          'file directly from disk will not work — use the CloudFront URL from ' +
          'the static-site stack output.',
      );
      return;
    }

    var params = new URLSearchParams(global.location.search);
    var boot;
    if (params.get('error')) {
      fatal(
        'Sign-in was rejected: ' + params.get('error'),
        params.get('error_description') ||
          'Check that this page URL is registered as a callback URL on the Cognito app client.',
      );
      return;
    }
    if (params.get('code')) {
      var expected = sessionStorage.getItem(STORE_STATE);
      if (!expected || params.get('state') !== expected) {
        fatal(
          'Sign-in could not be completed.',
          'The login response did not match this browser session. Reload the page to try again.',
        );
        return;
      }
      boot = exchangeCode(params.get('code'));
    } else if (validToken()) {
      boot = Promise.resolve();
    } else {
      boot = beginLogin();
    }

    boot.then(pageInit).catch(function (e) {
      fatal('Sign-in failed.', e.message);
    });
  }

  global.RFP = {
    start: start,
    fatal: fatal,
    identity: identity,
    logout: logout,
    config: function () { return cfg; },
    uploadApi: function (path, method, body) { return call(cfg.uploadApiUrl, path, method, body); },
    reviewApi: function (path, method, body) { return call(cfg.reviewApiUrl, path, method, body); },
  };
})(window);
