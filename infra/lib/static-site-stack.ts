import * as cdk from 'aws-cdk-lib';
import * as s3 from 'aws-cdk-lib/aws-s3';
import * as s3deploy from 'aws-cdk-lib/aws-s3-deployment';
import * as cloudfront from 'aws-cdk-lib/aws-cloudfront';
import * as origins from 'aws-cdk-lib/aws-cloudfront-origins';
import { Construct } from 'constructs';
import * as path from 'path';

export interface StaticSiteStackProps extends cdk.StackProps {
  readonly uploadApiUrl: string;
  readonly reviewApiUrl: string;
  readonly userPoolId: string;
  readonly userPoolClientId: string;
  /** Hosted UI origin, e.g. `https://<prefix>.auth.<region>.amazoncognito.com`. */
  readonly hostedUiUrl: string;
}

/**
 * Static UI on CloudFront + S3, served from the CloudFront-issued domain.
 *
 * No custom domain and no ACM certificate: DNS validation can stall a deploy
 * for hours, and the PoC has no domain of its own to validate against. Point a
 * CNAME at the CloudFrontDomain output later if a branded URL is wanted — that
 * is an additive change, not a rework.
 *
 * The pages carry no endpoint literals. Everything environment-specific is
 * deployed beside them as `config.js`, generated here from this synthesis's own
 * stack outputs, so a fresh deploy into a fresh account produces a UI that
 * talks to *that* account. The previous arrangement — API Gateway URLs typed
 * into the HTML — silently pointed a freshly deployed demo at a deleted
 * account's endpoints.
 */
export class StaticSiteStack extends cdk.Stack {
  public readonly distributionDomainName: string;

  constructor(scope: Construct, id: string, props: StaticSiteStackProps) {
    super(scope, id, props);

    const siteBucket = new s3.Bucket(this, 'SiteBucket', {
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      enforceSSL: true,
      autoDeleteObjects: true,
      removalPolicy: cdk.RemovalPolicy.DESTROY,
    });

    const distribution = new cloudfront.Distribution(this, 'SiteDistribution', {
      defaultBehavior: {
        origin: origins.S3BucketOrigin.withOriginAccessControl(siteBucket),
        viewerProtocolPolicy: cloudfront.ViewerProtocolPolicy.REDIRECT_TO_HTTPS,
        cachePolicy: cloudfront.CachePolicy.CACHING_DISABLED, // demo: always fresh
      },
      defaultRootObject: 'upload.html',
      errorResponses: [
        { httpStatus: 403, responseHttpStatus: 200, responsePagePath: '/upload.html' },
        { httpStatus: 404, responseHttpStatus: 200, responsePagePath: '/upload.html' },
      ],
    });

    this.distributionDomainName = distribution.distributionDomainName;

    // Deploy-time configuration. `Source.data` resolves the CDK tokens below
    // into an Fn::Sub at synth, so the object the browser sees holds the real
    // endpoints of whatever account this was deployed into.
    //
    // The shape is mirrored by REQUIRED_KEYS in ui/auth.js: a page that loads
    // a config missing any of these refuses to make a single call and says so
    // on screen, rather than failing one fetch at a time into the console.
    const config = {
      uploadApiUrl: props.uploadApiUrl,
      reviewApiUrl: props.reviewApiUrl,
      auth: {
        region: this.region,
        userPoolId: props.userPoolId,
        userPoolClientId: props.userPoolClientId,
        hostedUiUrl: props.hostedUiUrl,
        scopes: 'openid email profile',
      },
    };

    new s3deploy.BucketDeployment(this, 'DeployUI', {
      sources: [
        s3deploy.Source.asset(path.join(__dirname, '../../ui')),
        s3deploy.Source.data(
          'config.js',
          '// Generated by the static-site stack at deploy time. Do not edit.\n' +
            `window.RFP_CONFIG = ${JSON.stringify(config, null, 2)};\n`,
        ),
      ],
      destinationBucket: siteBucket,
      distribution,
      distributionPaths: ['/*'],
    });

    new cdk.CfnOutput(this, 'CloudFrontDomain', {
      value: distribution.distributionDomainName,
    });

    new cdk.CfnOutput(this, 'SiteUrl', {
      value: `https://${distribution.distributionDomainName}`,
    });

    // Second-pass hint: this is the value that has to reach the Cognito
    // callback list via `-c siteUrl=…`.
    new cdk.CfnOutput(this, 'CognitoCallbackContext', {
      value: `-c siteUrl=https://${distribution.distributionDomainName}`,
    });
  }
}
